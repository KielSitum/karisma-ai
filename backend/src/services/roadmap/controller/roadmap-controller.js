import { GoogleGenAI } from "@google/genai";

const ai = new GoogleGenAI({
  apiKey: process.env.GEMINI_API_KEY,
});

export const generateRoadmap = async (req, res) => {
  try {
    console.log("===== ROADMAP REQUEST =====");
    console.log("API KEY EXISTS:", !!process.env.GEMINI_API_KEY);
    console.log("REQ BODY:", req.body);

    const { skillGaps } = req.body;

    // Input validation
    if (!skillGaps || !Array.isArray(skillGaps) || skillGaps.length === 0) {
      return res.status(400).json({
        success: false,
        message: "skillGaps must be a non-empty array.",
      });
    }

    const skillList = skillGaps.join(", ");

    const prompt = `
You are an experienced career mentor.

Create an intensive 4-week learning roadmap for university students who want to master the following skills from a beginner level:

${skillList}

CRITICAL RULES:
- Reply ONLY with a valid JSON
- Do not use markdown
- Do not use \`\`\`
- Do not add any explanations outside of the JSON
- Use english language only

JSON Format:
{
  "summary": "Brief motivational summary",
  "weeks": [
    {
      "week": 1,
      "theme": "Week theme",
      "goals": ["Goal 1", "Goal 2"],
      "tasks": [
        {
          "day": "Monday - Tuesday",
          "activity": "Learning activity",
          "skill": "Skill being learned",
          "resources": "Learning resources"
        }
      ]
    }
  ],
  "tips": [
    "Tip 1",
    "Tip 2",
    "Tip 3"
  ]
}
`.trim();

    console.log("Generating roadmap...");

    const response = await ai.models.generateContent({
      model: "gemini-2.5-flash",
      contents: prompt,
    });

    console.log("FULL RESPONSE:", response);

    // Safely retrieve the text response
    const rawText = response.text || response.candidates?.[0]?.content?.parts?.[0]?.text;

    console.log("RAW TEXT:", rawText);

    if (!rawText) {
      return res.status(500).json({
        success: false,
        message: "AI did not return any response.",
      });
    }

    // Clean up markdown wrapper if accidently generated by the AI
    const cleanText = rawText
      .replace(/```json/g, "")
      .replace(/```/g, "")
      .trim();

    console.log("CLEAN TEXT:", cleanText);

    let roadmap;

    // Safely parse JSON
    try {
      roadmap = JSON.parse(cleanText);
    } catch (parseError) {
      console.error("JSON PARSE ERROR:", parseError);

      return res.status(500).json({
        success: false,
        message: "Invalid JSON format received from AI.",
        raw: cleanText,
      });
    }

    return res.status(200).json({
      success: true,
      skillGaps,
      roadmap,
    });

  } catch (error) {
    console.error("===== GEMINI ERROR =====");
    console.error(error);

    return res.status(500).json({
      success: false,
      message: error.message || "An internal server error occurred.",
    });
  }
};